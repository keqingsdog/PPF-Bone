class JUPYTER_OT_Export(Operator):
    """Export a JupyterLab notebook via the solver server."""

    bl_idname = "solver.jupyter_export"
    bl_label = "Export"

    filepath: _ppf_props.StringProperty(  # pyright: ignore
        name="Path",
        description="Notebook path relative to JupyterLab root",
        default="",
    )

    @classmethod
    def poll(cls, context):
        return com.is_connected()

    def invoke(self, context, event):
        state = get_addon_data(context.scene).state
        last = state.jupyter_last_export.strip()
        if last:
            self.filepath = last
        else:
            name = state.project_name.strip() or "unnamed"
            self.filepath = f"blender-export/{name}.ipynb"
        return context.window_manager.invoke_props_dialog(self)

    def draw(self, context):
        self.layout.prop(self, "filepath")

    def execute(self, context):
        filepath = self.filepath.strip()
        if not filepath:
            self.report({"ERROR"}, iface_("Filepath is empty"))
            return {"CANCELLED"}
        if not filepath.endswith(".ipynb"):
            self.report({"ERROR"}, iface_("Filename must end with .ipynb"))
            return {"CANCELLED"}

        state = get_addon_data(context.scene).state
        # `{project_name}` in the template feeds `BlenderApp.open(...)`,
        # which keys off the project name on the remote server (the
        # data path is `<data_dir>/<project_name>`), NOT the notebook
        # filename. Using the filename stem here meant a user-renamed
        # notebook ("tree-my.ipynb") generated `BlenderApp.open("tree-my")`
        # for a project the server actually stores as "tree", and the
        # notebook failed to load. Fall back to the filename stem only
        # when the addon's project_name field is empty.
        project_name = state.project_name.strip() or (
            filepath.rsplit("/", 1)[-1].removesuffix(".ipynb")
        )

        connection = com.connection
        if not connection.instance or not com.is_connected():
            self.report({"ERROR"}, iface_("Not connected to solver server. Connect first."))
            return {"CANCELLED"}
        # Ask this backend about this project now: cached UI response and the
        # connection directory do not identify the uploaded project directory.
        try:
            response, alive = connection.instance.query({}, project_name)
            project_root = response.get("root") if isinstance(response, dict) else None
            if (not alive or not isinstance(project_root, str) or not project_root
                    or "\x00" in project_root
                    or not ((ntpath.isabs(project_root) and ntpath.splitdrive(project_root)[0])
                            or posixpath.isabs(project_root))):
                raise ValueError("服务器未返回当前项目的有效绝对目录；请先传输项目后重试导出")
            frontend_bootstrap = ""
            if connection.instance.backend_type == "win_native":
                source = Path(connection.instance.current_directory)
                if not source.is_absolute():
                    raise ValueError("当前本地后端未提供有效源码绝对目录")
                source = source.resolve(strict=True)
                if not (source / "frontend" / "__init__.py").is_file():
                    raise ValueError("当前本地后端源码目录缺少 frontend 入口")
                # Embedded Windows Python ignores PYTHONPATH. The exported
                # notebook must identify the connected source tree itself.
                frontend_bootstrap = (
                    "from pathlib import Path as _PPFPath\n"
                    "import sys as _ppf_sys\n"
                    f"_ppf_source = _PPFPath({json.dumps(str(source), ensure_ascii=False)}).resolve(strict=True)\n"
                    "_ppf_package = (_ppf_source / 'frontend').resolve(strict=True)\n"
                    "_ppf_entry = (_ppf_package / '__init__.py').resolve(strict=True)\n"
                    "for _ppf_name, _ppf_module in tuple(_ppf_sys.modules.items()):\n"
                    "    if _ppf_name == 'frontend' or _ppf_name.startswith('frontend.'):\n"
                    "        _ppf_file = getattr(_ppf_module, '__file__', None)\n"
                    "        if not _ppf_file or not _PPFPath(_ppf_file).resolve().is_relative_to(_ppf_package):\n"
                    "            raise RuntimeError('已加载其他或来源不明的 frontend；请重启内核 / Restart Kernel 后重试')\n"
                    "_ppf_sys.path.insert(0, str(_ppf_source))\n"
                    "import frontend as _ppf_frontend\n"
                    "if _PPFPath(_ppf_frontend.__file__).resolve() != _ppf_entry:\n"
                    "    raise RuntimeError('frontend 来源与当前后端不符；请重启内核 / Restart Kernel')\n"
                )
        except Exception as exc:
            self.report({"ERROR"}, iface_("Export failed: {error}").format(error=str(exc)))
            return {"CANCELLED"}
        project_literal = json.dumps(project_name, ensure_ascii=False)
        root_literal = json.dumps(project_root, ensure_ascii=False)

        notebook = copy.deepcopy(JUPYTER_NOTEBOOK_TEMPLATE)
        for cell in notebook["cells"]:
            cell["source"] = [
                line.format_map({"project_name": project_name, "project_literal": project_literal, "root_literal": root_literal, "frontend_bootstrap": frontend_bootstrap})
                for line in cell["source"]
            ]
        payload = json.dumps(notebook).encode("utf-8")

        # Route the write through the solver server instead of JupyterLab's
        # contents API. Hitting /api/contents was making the exported file
        # (and its parent `blender-export/` dir) vanish after a while
        # (suspected interaction with JupyterLab's cloned-workspace state).
        # The server resolves relative_path against <src>/examples/.
        connection = com.connection
        if not connection.instance or not com.is_connected():
            self.report({"ERROR"}, iface_("Not connected to solver server. Connect first."))
            return {"CANCELLED"}

        ok, rejected, err = _notebook_request(
            connection,
            {
                "request": "notebook_send",
                "relative_path": filepath,
                "size": len(payload),
                "name": project_name,
            },
            payload=payload,
        )
        if not ok:
            if rejected:
                self.report({"ERROR"}, iface_("Server rejected notebook: {error}").format(error=err))
            else:
                self.report({"ERROR"}, iface_("Export failed: {error}").format(error=err))
            return {"CANCELLED"}

        state.jupyter_last_export = filepath
        self.report({"INFO"}, iface_("Exported {path} via solver server").format(path=filepath))
        redraw_all_areas(context)
        return {"FINISHED"}


class JUPYTER_OT_OpenURL(Operator):
    """Open the JupyterLab notebook in a browser."""

    bl_idname = "solver.jupyter_open"
    bl_label = "Open URL"

    @classmethod
    def poll(cls, context):
        return bool(get_addon_data(context.scene).state.jupyter_last_export.strip())

    def execute(self, context):
        state = get_addon_data(context.scene).state
        port = state.jupyter_port
        path = state.jupyter_last_export.strip()
        url = f"http://localhost:{port}/lab/tree/{path}"
        webbrowser.open(url)
        self.report({"INFO"}, iface_("Opened {url}").format(url=url))
        return {"FINISHED"}


class JUPYTER_OT_Delete(Operator):
    """Delete the exported notebook via the solver server."""

    bl_idname = "solver.jupyter_delete"
    bl_label = "Delete"

    @classmethod
    def poll(cls, context):
        state = get_addon_data(context.scene).state
        return com.is_connected() and bool(state.jupyter_last_export.strip())

    def execute(self, context):
        state = get_addon_data(context.scene).state
        filepath = state.jupyter_last_export.strip()
        project_name = filepath.rsplit("/", 1)[-1].removesuffix(".ipynb")

        connection = com.connection
        if not connection.instance or not com.is_connected():
            self.report({"ERROR"}, iface_("Not connected to solver server. Connect first."))
            return {"CANCELLED"}

        ok, rejected, err = _notebook_request(
            connection,
            {
                "request": "notebook_delete",
                "relative_path": filepath,
                "name": project_name,
            },
        )
        if not ok:
            if rejected:
                self.report({"ERROR"}, iface_("Server rejected delete: {error}").format(error=err))
            else:
                self.report({"ERROR"}, iface_("Delete failed: {error}").format(error=err))
            return {"CANCELLED"}

        state.jupyter_last_export = ""
        self.report({"INFO"}, iface_("Deleted {path}").format(path=filepath))
        redraw_all_areas(context)
        return {"FINISHED"}


classes = (
    JUPYTER_OT_Export,
    JUPYTER_OT_OpenURL,
    JUPYTER_OT_Delete,
)


def register():
    for cls in classes:
        _ppf_i18n.register_class(cls)


def unregister():
    for cls in reversed(classes):
        bpy.utils.unregister_class(cls)
