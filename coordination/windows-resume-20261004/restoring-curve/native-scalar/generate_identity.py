"""Generate checked source identity from actual kernelgen layouts/ordered table."""
from pathlib import Path
import re,hashlib,importlib.util,json,argparse
ROOT=Path(__file__).resolve().parents[4];KERNEL=ROOT/'crates/ppf-cts-solver/src/kernels'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
spec=importlib.util.spec_from_file_location('kg',ROOT/'crates/ppf-cts-compute/seam/kernelgen.py');kg=importlib.util.module_from_spec(spec);spec.loader.exec_module(kg);kg.KERNEL_ROOT=str(KERNEL)
build=(ROOT/'crates/ppf-cts-solver/build.rs').read_text(encoding='utf8')
kernels=re.findall(r'"([^"]+)"',re.search(r'const KERNELS:.*?=\s*\[(.*?)\];',build,re.S).group(1))
handles=re.findall(r'\("([^"]+)",\s*"([^"]+)"\)',re.search(r'const HANDLE_FIELDS:.*?=\s*&\[(.*?)\];',build,re.S).group(1))
def canonical(text):
    return re.sub(r'\s+',' ',re.sub(r'//[^\n]*','',text)).strip()
pod=(ROOT/'crates/ppf-cts-solver/src/restoring_curve_gpu.rs').read_text(encoding='utf8')
layout_spec=re.search(r'pub const LAYOUT_SPEC:&str="([^"]+)"',pod).group(1)
angular_pod=(ROOT/'crates/ppf-cts-solver/src/joint_angular_extension_gpu.rs').read_text(encoding='utf8')
angular_layout_spec=re.search(r'pub const ANGULAR_EXTENSION_LAYOUT_SPEC\s*:\s*&str\s*=\s*"([^"]+)"',angular_pod).group(1)
layouts=[];tables=[];entry_count=0
for stem in kernels:
    source=str(KERNEL/(stem+'.kernel.cpp'))
    _,_,_,entries=kg.read_source(source)
    tables.append(stem+'\n'+canonical(kg.render_table_rust(source,entries)))
    entry_count+=sum(e.emit_entry for e in entries)
    if stem=='zzzzzzzzz_restoring/restoring_apply':
        migrated=[field for owner,field in handles if owner==stem]
        layouts.append(canonical(kg.render_entry_rust(source,entries,migrated)))
layout_hash=hashlib.sha256((layout_spec+'\n'+angular_layout_spec+'\n'+'\n'.join(layouts)).encode()).digest()
table_hash=hashlib.sha256('\n'.join(tables).encode()).digest()
source_hash=hashlib.sha256()
for f in sorted([KERNEL/'zz_joint_ext/restoring_curve.hpp',KERNEL/'zz_joint_ext/restoring_context.hpp',KERNEL/'zz_joint_ext/restoring_observation.hpp',KERNEL/'energy/model/restoring_stitch.hpp',KERNEL/'zzzzzzzzz_restoring/restoring_apply.kernel.cpp']):source_hash.update(f.relative_to(ROOT).as_posix().encode());source_hash.update(f.read_bytes())
stamp=source_hash.hexdigest()
# Senior PASS_SOURCE_AND_SCOPED_DATASET permits the compiled capability candidate.
# Production CUDA/native acceptance remains a separate root-owned gate.
mask=15
rust='// Generated by native-scalar/generate_identity.py; do not hand-edit.\n'
rust+=f'pub const RESTORING_CURVE_SOURCE_STAMP:&str="{stamp}";\npub const RESTORING_CURVE_CONTRACT_VERSION:u32=1;\npub const RESTORING_CURVE_CHANNEL_MASK:u32={mask};\n'
for name,data in [('LAYOUT',layout_hash),('KERNEL_TABLE',table_hash)]:rust+=f'pub const RESTORING_CURVE_{name}_SHA256:[u8;32]=['+','.join(str(v) for v in data)+'];\n'
header='#pragma once\n// Generated by native-scalar/generate_identity.py; do not hand-edit.\n#define PPF_RESTORING_CURVE_CONTRACT_VERSION 1u\n'+f'#define PPF_RESTORING_CURVE_CHANNEL_MASK {mask}u\n'
for name,size,align in [('DESCRIPTOR',32,4),('NODE',16,4),('BINDING',48,4),('HISTORY',32,8)]:header+=f'#define PPF_RESTORING_{name}_SIZE {size}u\n#define PPF_RESTORING_{name}_ALIGN {align}u\n'
for name,data in [('LAYOUT',layout_hash),('KERNEL_TABLE',table_hash)]:header+=f'static const unsigned char PPF_RESTORING_CURVE_{name}_SHA256[32]={{'+','.join(str(v) for v in data)+'};\n'
outputs={ROOT/'crates/ppf-cts-compute/src/restoring_curve_identity.rs':rust,KERNEL/'seam/restoring_curve_identity.h':header}
for file,text in outputs.items():
    if args.check:assert file.read_text(encoding='utf8')==text,f'STALE_COMPILED_RESTORING_IDENTITY: {file}'
    else:file.write_text(text,encoding='utf8',newline='\n')
receipt={'status':'COMPILED_CAPABILITY_CANDIDATE_NOT_NATIVE_PASS','contract_version':1,'channel_mask':mask,'ordered_entry_count':entry_count,'layout_sha256':layout_hash.hex(),'kernel_table_sha256':table_hash.hex(),'source_stamp':stamp,'serialization':'UTF8 frozen LAYOUT_SPEC newline then whitespace-normalized actual kernelgen Rust arg struct/assert source; ordered table stem newline whitespace-normalized Rust table source, newline joined, includes all legacy entries; comments omitted'}
if not args.check:(Path(__file__).parent/'compiled-identity.json').write_text(json.dumps(receipt,indent=2),encoding='utf8')
print(json.dumps(receipt))
